/** 随机取一个初始事件 */
export function pickInitialEvent() {
  return INITIAL_EVENTS[Math.floor(Math.random() * INITIAL_EVENTS.length)]
}

/** 按概率抽黑天鹅事件（返回 null 表示本回合无事发生） */
export function maybeShockEvent(probability = 0.35) {
  if (Math.random() > probability) return null
  return SHOCK_EVENTS[Math.floor(Math.random() * SHOCK_EVENTS.length)]
}
